/**
 * Generates supabase/seed.sql from the typed content files in src/content,
 * so the database and the app always share one source of truth.
 * Run: npm run db:seed:generate
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { CATEGORIES, destinations } from "../src/content/destinations";
import { dishes, eras } from "../src/content/culture";
import { events, prices } from "../src/content/practical";
import { walks } from "../src/content/walks";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (a: (string | number)[], type: string) => `array[${a.map(q).join(",")}]::${type}[]`;
const slugify = (s: string) => s.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const out: string[] = ["-- GENERATED by scripts/generate-seed.ts — do not edit by hand.", "begin;"];

out.push(...CATEGORIES.map((c) => `insert into public.categories (slug, name) values (${q(slugify(c))}, ${q(c)}) on conflict (slug) do update set name = excluded.name;`));

for (const d of destinations) {
  out.push(
    `insert into public.destinations (slug, name, region, category_slug, environment, lat, lng, tagline, summary, interests, min_budget_level, ideal_days, best_months, hidden_gem, photo_key, passport_fact) values (` +
      [q(d.slug), q(d.name), q(d.region), q(slugify(d.category)), q(d.environment), q(d.lat), q(d.lng), q(d.tagline), q(d.summary), `${q(JSON.stringify(d.interests))}::jsonb`, q(d.minBudgetLevel), `int4range(${d.idealDays[0]}, ${d.idealDays[1]}, '[]')`, arr(d.bestMonths, "smallint"), q(d.hiddenGem), q(d.photo), q(d.passportFact)].join(", ") +
      `) on conflict (slug) do update set name = excluded.name, tagline = excluded.tagline, summary = excluded.summary, interests = excluded.interests, best_months = excluded.best_months;`,
  );
  d.attractions.forEach((a, i) =>
    out.push(`insert into public.attractions (destination_slug, name, note, sort) values (${q(d.slug)}, ${q(a.name)}, ${q(a.note)}, ${i}) on conflict (destination_slug, name) do update set note = excluded.note, sort = excluded.sort;`),
  );
}

for (const f of dishes) {
  out.push(
    `insert into public.food (slug, name, arabic, kind, description, ingredients, price_min_egp, price_max_egp, vegetarian, background) values (` +
      [q(f.slug), q(f.name), q(f.arabic), q(f.kind), q(f.description), arr(f.ingredients, "text"), q(f.priceRange?.[0] ?? null), q(f.priceRange?.[1] ?? null), q(f.vegetarian), q(f.background)].join(", ") +
      `) on conflict (slug) do nothing;`,
  );
}

eras.forEach((e, i) =>
  out.push(`insert into public.historical_stories (id, name, dates, summary, child_version, place_slugs, sort) values (${[q(e.id), q(e.name), q(e.dates), q(e.summary), q(e.childVersion), arr(e.places, "text"), i].join(", ")}) on conflict (id) do nothing;`),
);

for (const w of walks) {
  out.push(`insert into public.walking_routes (slug, title, duration, distance_km, intro, tips, status) values (${[q(w.slug), q(w.title), q(w.duration), q(w.distanceKm), q(w.intro), arr(w.tips, "text"), q(w.status)].join(", ")}) on conflict (slug) do nothing;`);
  w.stops.forEach((s, i) =>
    out.push(`insert into public.route_stops (route_slug, position, name, lat, lng, minutes, story) values (${[q(w.slug), i, q(s.name), q(s.lat), q(s.lng), q(s.minutes), q(s.story)].join(", ")}) on conflict (route_slug, position) do nothing;`),
  );
}

for (const e of events) {
  out.push(
    `insert into public.events (id, name, location, when_text, date_iso, description, status, last_verified, source_name, source_url) values (` +
      [q(e.id), q(e.name), q(e.where), q(e.when), q(e.dateISO), q(e.description), q(e.status), q(e.lastVerified), q(e.source?.name ?? null), q(e.source?.url ?? null)].join(", ") +
      `) on conflict (id) do nothing;`,
  );
}

for (const p of prices) {
  out.push(
    `insert into public.travel_prices (id, item, min_egp, max_egp, kind, status, last_verified, source_name, source_url) values (` +
      [q(p.id), q(p.item), q(p.egp[0]), q(p.egp[1]), q(p.kind), q(p.status), q(p.lastVerified), q(p.source?.name ?? null), q(p.source?.url ?? null)].join(", ") +
      `) on conflict (id) do nothing;`,
  );
}

out.push(`insert into public.site_settings (key, value) values ('featured_destinations', '["giza","luxor","aswan","dahab","siwa"]'::jsonb) on conflict (key) do nothing;`);
out.push("commit;", "");

const file = path.join(__dirname, "..", "supabase", "seed.sql");
writeFileSync(file, out.join("\n"));
console.log(`Wrote ${out.length - 3} statements to ${path.relative(process.cwd(), file)}`);
